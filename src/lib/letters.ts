/**
 * Duty letters — «… үүрэг, хариуцлагыг хүлээн зөвшөөрсөн тухай албан бичиг». Every new head and member
 * signs one at the Их Хуралдаан (Үндсэн дүрэм 18.1.3), the President signs theirs with the previous
 * President. The wording is the association's 2026 template; names, departments, student IDs and terms
 * come from the member list, so the department can no longer be copied wrong from last year's file.
 */
import type { StaffPerson } from './team';
import { fmtOfficial } from './time';

export interface LetterSection {
  heading: string;
  paragraphs?: string[];
  facts?: [string, string][];
  items?: string[];
}
export interface Letter {
  person: StaffPerson;
  kind: string;
  sections: LetterSection[];
  signers: { title: string; names: string[] }[];
}

/** Heads, members and the President sign one. Board members and the maintainer don't. */
export const needsLetter = (p: StaffPerson) => p.role === 'president' || p.role === 'head' || p.role === 'member';

const EFFECT = [
  'Энэхүү албан бичигт гарын үсэг зурсан мөчөөс эхлэн хүчин төгөлдөр үйлчилнэ.',
  'Албан тушаалтан өөрийн хүсэлтээр, сайн дурын үндсэн дээр албан тушаалаасаа чөлөөлөгдөх хүсэлт гаргавал энэхүү албан бичиг хүчингүй болно. Тухайн хүсэлтийг Удирдах Зөвлөл хэлэлцэн баталгаажуулна.',
  'Албан тушаалтан болон Холбоо харилцан зөвшилцөж хамтын ажиллагаагаа дуусгавар болгох шийдвэр гаргаж болох бөгөөд энэ тохиолдолд албан ёсны тэмдэглэл үйлдэж, архивт хадгална.',
  'Холбоо нь бүх гишүүдийн тэгш, шударга байдлыг хангах үүднээс шийдвэрээ олон нийтэд ил тод зарлаж, дотоод архивт тэмдэглэнэ.',
];

export function buildLetter(p: StaffPerson, president: string, start: number): Letter {
  const term = `${fmtOfficial(start)} – ${fmtOfficial(p.term_ends_at)}`;
  const sid = p.student_id || '________________';

  if (p.role === 'president') {
    return {
      person: p,
      kind: 'ХОЛБООНЫ ТЭРГҮҮНИЙ ҮҮРЭГ, ХАРИУЦЛАГЫГ ХҮЛЭЭН ЗӨВШӨӨРСӨН ТУХАЙ АЛБАН БИЧИГ',
      sections: [
        {
          heading: 'Нэг. Ерөнхий заалт',
          paragraphs: [
            'Энэхүү бичиг нь Бээжингийн Их Сургуулийн Монгол Оюутны Холбоо (цаашид «Холбоо» гэх)-ны Тэргүүнээр сонгогдсон гишүүний эрх, үүрэг, хариуцлагыг тодорхойлж, Холбооны Үндсэн дүрэм, журам, дотоод зохицуулалтыг чанд мөрдөхийг баталгаажуулах зорилготой болно.',
          ],
        },
        {
          heading: 'Хоёр. Албан тушаалтны мэдээлэл',
          facts: [
            ['Овог, нэр', p.name],
            ['Оюутны дугаар', sid],
            ['Албан тушаал', 'Бээжингийн Их Сургуулийн Монгол Оюутны Холбооны Тэргүүн'],
            ['Албан тушаалын хугацаа', term],
          ],
        },
        {
          heading: 'Гурав. Эрх, үүрэг',
          paragraphs: ['Тэргүүн дараах эрх, үүргийг хэрэгжүүлнэ:'],
          items: [
            'Холбоог бүх талаар төлөөлж, дотоод болон гадаад харилцаанд албан ёсоор оролцох;',
            'Холбооны үйл ажиллагааны ерөнхий чиглэл, бодлогыг тодорхойлж удирдах;',
            'Удирдах Зөвлөлийн хурлыг зохион байгуулж, хэлэлцэх асуудлыг шийдвэрлүүлэх;',
            'Бусад гишүүдийн үйл ажиллагааг уялдуулан зохицуулж, ажлын тайланг хянан батлах;',
            'Холбооны төсөв, санхүүгийн зарцуулалтад хяналт тавьж, тайлагнах;',
            'Холбооны нэр хүндийг хамгаалж, эв нэгдлийг хангах, дотоод болон гадаад талд итгэлцлийг бий болгох.',
          ],
        },
        {
          heading: 'Дөрөв. Холбооны эрх, зохицуулалт',
          items: [
            'Тэргүүн дээр дурдсан үүргээ биелүүлээгүй, эсхүл Холбооны дүрэм, журам, ёс зүйг үл хүндэтгэсэн тохиолдолд Холбоо түүнийг албан тушаалаас нь чөлөөлөх эрхтэй.',
            'Тэргүүн өөрийн хүсэлтээр, сайн дураар чөлөөлөгдөх хүсэлт гаргаж болно.',
            'Холбоо болон Тэргүүн харилцан зөвшилцөж хамтын ажиллагаагаа дуусгавар болгох шийдвэр гаргаж болох бөгөөд энэ тохиолдолд албан ёсны тэмдэглэл үйлдэж, архивт хадгална.',
          ],
        },
        { heading: 'Тав. Хүчин төгөлдөр байдал', items: EFFECT },
      ],
      signers: [
        { title: 'Холбооны Тэргүүн', names: [p.name] },
        { title: 'Холбооны өмнөх Тэргүүн', names: [''] },
      ],
    };
  }

  const head = p.role === 'head';
  const roleGen = head ? 'Хэлтсийн даргын' : 'Хэлтсийн гишүүний';
  return {
    person: p,
    kind: `${roleGen.toUpperCase()} ҮҮРЭГ, ХАРИУЦЛАГЫГ ХҮЛЭЭН ЗӨВШӨӨРСӨН ТУХАЙ АЛБАН БИЧИГ`,
    sections: [
      {
        heading: 'Нэг. Ерөнхий заалт',
        paragraphs: [
          `Энэхүү бичиг нь Бээжингийн Их Сургуулийн Монгол Оюутны Холбоо (цаашид «Холбоо» гэх)-ны дотоод зохион байгуулалтын хүрээнд сонгогдсон ${roleGen} нэр, албан тушаал, хариуцлага болон Холбооны Үндсэн дүрэм, журмыг дагаж мөрдөхийг баталгаажуулах зорилготой болно. Энэхүү албан бичиг нь хуулийн шинж чанаргүй бөгөөд хуулийн ямар нэгэн хариуцлага үүсгэхгүй.`,
        ],
      },
      {
        heading: 'Хоёр. Албан тушаалтны мэдээлэл',
        facts: [
          ['Овог, нэр', p.name],
          ['Албан тушаал', head ? 'Хэлтсийн дарга' : 'Хэлтсийн гишүүн'],
          ['Хэлтэс', p.dept_name ?? ''],
          ['Оюутны дугаар', sid],
          ['Албан тушаалын хугацаа', term],
        ],
      },
      {
        heading: 'Гурав. Үүрэг, хариуцлага',
        paragraphs: ['Та дараах хариуцлагыг өөрийн хэлтэс, албан тушаалын хүрээнд хүлээнэ.'],
        items: [
          'Холбооны Үндсэн дүрэм, журам, дотоод зохицуулалтыг чанд сахих;',
          head
            ? 'Өөрийн хариуцсан багийн үйл ажиллагааг удирдан зохион байгуулж, ажлын тайланг тогтмол гаргах;'
            : 'Хэлтсийнхээ үйл ажиллагаанд идэвхтэй оролцож, хүлээсэн ажлаа хугацаанд нь гүйцэтгэх;',
          'Бусад гишүүдтэй харилцан уялдаатай ажиллаж, Холбооны үйл ажиллагааг тасралтгүй, үр дүнтэй хэрэгжүүлэх;',
          'Холбооны нэр хүндийг сахин хамгаалж, эв нэгдэл, хамтын ажиллагааг дэмжих;',
          'Сонгогдсон хугацаандаа үүргээ үнэнч шударгаар биелүүлэх;',
          'Холбооны дотоод үйл ажиллагаатай холбоотой дүрэм, журам, бодлого, шийдвэр, хурлын тэмдэглэл, гишүүдийн мэдээлэл болон нийтэд ил тод бус бусад мэдээллийг Холбооны зөвшөөрөлгүйгээр гуравдагч этгээдэд задруулах, дамжуулах, нийтэд түгээхгүй байх. Энэхүү нууцлалын үүргийг албан тушаалын хугацаа дууссан, эсхүл албан тушаалаас чөлөөлөгдсөнөөс хойш ч үргэлжлүүлэн мөрдөнө.',
        ],
      },
      {
        heading: 'Дөрөв. Холбооны эрх, дэгийн хариуцлага',
        items: [
          'Гишүүн дээр дурдсан үүргээ биелүүлэхээс татгалзсан, эсхүл Үндсэн дүрэм, журмыг үл хүндэтгэсэн тохиолдолд Холбоо тухайн гишүүнийг албан тушаалаас нь чөлөөлөх, эрх хэмжээг нь хязгаарлах эрхтэй.',
          'Холбоо үүргээ биелүүлээгүй гишүүний хариуцлагыг хэлэлцэж, шаардлагатай гэж үзвэл Удирдах Зөвлөл болон Хуралдаанаар шийдвэр гаргаж, албан ёсоор хүчингүй болгоно.',
        ],
      },
      { heading: 'Тав. Хүчин төгөлдөр байдал', items: EFFECT },
    ],
    signers: [
      { title: 'Холбооны Тэргүүн', names: [president] },
      { title: 'Албан тушаалтан', names: [p.name] },
    ],
  };
}
